# ============================================================================
# Empirical calibration — Step 1: clean the ZUDPEP bean trial exports
# ============================================================================
# Source: Harvard Dataverse doi:10.7910/DVN/ZUDPEP (CC0), Ugandan national bean
# program; Amongi et al. 2019, J. Agric. Sci. 11(13):81, 10.5539/jas.v11n13p81.
# Input : 33 Breeding Management System (BMS) exports, one per trial
#         (site x season), each with a plot-level "Observation" sheet.
# Output: empirical/outputs/zudpep_plots.csv        (one row per plot)
#         empirical/outputs/zudpep_cleaning_log.md  (all cleaning decisions)
#
# Usage (from the project root):
#   Rscript empirical/R/01_zudpep_clean.R [path/to/ZUDPEP/x]

suppressPackageStartupMessages({
  library(data.table)
  library(readxl)
  library(lme4)
})

args    <- commandArgs(trailingOnly = TRUE)
raw_dir <- if (length(args) >= 1) args[1] else
  "data/external/bean_public_2026-10-10/datasets/ZUDPEP/x"
out_dir <- "empirical/outputs"
dir.create(out_dir, showWarnings = FALSE, recursive = TRUE)

# --- Cleaning constants -------------------------------------------------------
PLANTS_PER_HA   <- 200000   # density implied by the recorded YDHA = 200 * YDPL
MIN_PLANTS      <- 5        # minimum harvested plants for a per-plant yield
MIN_STAND_REL   <- 0.20     # minimum stand relative to the trial median
OUTLIER_Z       <- 3.5      # |standardized residual| threshold within a trial
DEFAULT_AREA_M2 <- 4.5      # effective plot area (PlotArea_m2 column)

log_lines <- character()
logl <- function(...) log_lines <<- c(log_lines, paste0(...))

# --- Trial series (set) from the file name ------------------------------------
series_of <- function(f) {
  fcase(grepl("^DABs? Set ?1 ", f, ignore.case = TRUE), "DAB_Set1",
        grepl("Set ?3",        f, ignore.case = TRUE), "DAB_Set3",
        grepl("Set 4",         f),                     "DAB_Set4",
        grepl("SET_2",         f),                     "DAB_Set2",
        grepl("Black Beans",   f),                     "DroughtBlack",
        grepl("Introduction",  f),                     "DroughtIntro",
        grepl("Coloured",      f),                     "DroughtColoured",
        grepl("Small Red",     f),                     "DroughtSmallRed",
        default = NA_character_)
}

site_of_file <- function(f) {
  fcase(grepl("Kawanda",    f), "Kawanda",
        grepl("Kachwekano", f), "Kachwekano",
        grepl("Kitengule",  f), "Kitengule",
        default = NA_character_)
}

season_of_file <- function(f) regmatches(f, regexpr("20[0-9]{2}[AB]", f))

# Value of a condition in the BMS "Description" sheet (column 7 = VALUE)
desc_value <- function(ds, key, col = 7) {
  i <- which(ds[[1]] == key)[1]
  if (is.na(i) || ncol(ds) < col) NA_character_ else as.character(ds[i, col])
}

# --- Read every export ----------------------------------------------------------
files <- sort(list.files(raw_dir, pattern = "\\.xlsx?$"))
stopifnot(length(files) > 0)
logl("# ZUDPEP cleaning log")
logl("")
logl("Generated by `empirical/R/01_zudpep_clean.R` on ", format(Sys.Date()), ".")
logl("Source: Harvard Dataverse doi:10.7910/DVN/ZUDPEP (CC0); ", length(files),
     " BMS exports, plot-level `Observation` sheets read as text.")
logl("")

meta <- list(); obs <- list()
for (f in files) {
  path <- file.path(raw_dir, f)
  sh   <- excel_sheets(path)
  md   <- data.table(source_file = f, study = NA_character_, desc_site = NA_character_,
                     design = NA_character_, start_date = NA_character_)
  if ("Description" %in% sh) {
    ds <- as.data.frame(suppressMessages(
      read_excel(path, sheet = "Description", col_names = FALSE, col_types = "text")))
    md[, `:=`(study      = ds[which(ds[[1]] == "STUDY")[1], 2],
              start_date = ds[which(ds[[1]] == "START DATE")[1], 2],
              desc_site  = desc_value(ds, "SITE_NAME"),
              design     = desc_value(ds, "EXPT_DESIGN"))]
  }
  meta[[f]] <- md

  x  <- as.data.table(suppressWarnings(suppressMessages(
    read_excel(path, sheet = "Observation", col_types = "text", .name_repair = "unique"))))
  nm <- names(x)
  col1 <- function(pattern) {
    m <- grep(pattern, nm, value = TRUE)
    if (length(m)) x[[m[1]]] else rep(NA_character_, nrow(x))
  }
  # One export lacks a DESIGNATION column; its first ENTRY_NO column holds the
  # line names and the second holds the entry numbers.
  if ("DESIGNATION" %in% nm) {
    desig <- x$DESIGNATION; entry <- col1("^ENTRY_NO")
  } else {
    en <- grep("^ENTRY_NO", nm, value = TRUE)
    desig <- x[[en[1]]]; entry <- x[[en[2]]]
  }
  obs[[f]] <- data.table(
    source_file = f, row_in_file = seq_len(nrow(x)),
    SITE = col1("^SITE$"), SEASON = col1("^SEASON$"),
    designation_raw = desig, entry_no = entry,
    rep = col1("^REP"), block = col1("^BLOCK"), plot_no = col1("^PLOT_NO"),
    PLPLOT = col1("^PLPLOT$"), GMPLOT = col1("^GMPLOT$"),
    YDPL = col1("^YDPL$"), YDHA = col1("^YDHA$"),
    PlotArea = col1("^PlotArea"))
}
meta <- rbindlist(meta)
dt   <- rbindlist(obs)
num_cols <- c("PLPLOT", "GMPLOT", "YDPL", "YDHA", "PlotArea", "rep", "block")
dt[, (num_cols) := lapply(.SD, function(z) suppressWarnings(as.numeric(z))), .SDcols = num_cols]
n_rows_read <- nrow(dt)

# --- 1. Remove rows that are not plots ------------------------------------------
dt[, designation_raw := trimws(designation_raw)]
no_id <- dt[is.na(designation_raw) | designation_raw == ""]
logl("## 1. Rows that are not plots")
logl("")
logl("- Rows read from all Observation sheets: ", n_rows_read, ".")
logl("- Removed ", nrow(no_id), " rows with no designation (blank trailing rows, ",
     "column summary rows, and unattached values below the plot table). ",
     "Rows of this kind carrying a yield-like value: ",
     no_id[!is.na(GMPLOT) | !is.na(YDHA), .N], ". By file:")
for (r in no_id[, .N, by = source_file][order(-N)][, sprintf("  - %s: %d", source_file, N)]) logl(r)
dt <- dt[!(is.na(designation_raw) | designation_raw == "")]
logl("")

# --- 2. Trial identity: series, site, season ------------------------------------
dt[, set := series_of(source_file)]
dt[, site := site_of_file(source_file)]
dt[, season := season_of_file(source_file)]
stopifnot(!anyNA(dt$set), !anyNA(dt$site), !anyNA(dt$season))

logl("## 2. Trial identity (series, site, season)")
logl("")
logl("- Trial series (`set`) is taken from the file name: ",
     paste(sort(unique(dt$set)), collapse = ", "), ". These match the BMS STUDY ",
     "names; each series was repeated across sites and seasons with the same entries.")
logl("- Site is taken from the file name. Cross-checks against the SITE column and ",
     "the Description sheet SITE_NAME:")
site_chk <- merge(dt[, .(site_col = paste(unique(SITE), collapse = "/")), by = .(source_file, site)],
                  meta[, .(source_file, desc_site)], by = "source_file")
mis <- site_chk[site_col != site]
for (i in seq_len(nrow(mis))) logl(sprintf(
  "  - `%s`: SITE column = %s, Description SITE_NAME = %s, file name = %s. Kept %s (file name and Description agree; KaZARDI is the Kachwekano station).",
  mis$source_file[i], mis$site_col[i], mis$desc_site[i], mis$site[i], mis$site[i]))
logl("  - All other files: SITE column equals the file-name site. Description SITE_NAME ",
     "uses the synonyms Kagera (= Kitengule, Kagera Region, Tanzania), NARL-Kawanda ",
     "(= Kawanda) and KaZARDI (= Kachwekano); some 2018 files leave it blank.")
seas_mis <- dt[SEASON != season, .N, by = .(source_file, SEASON, season)]
for (i in seq_len(nrow(seas_mis))) logl(sprintf(
  "- `%s`: %d plots carry SEASON = %s although the file is %s; they are rep-2 plots of the same layout, so the season was set to %s.",
  seas_mis$source_file[i], seas_mis$N[i], seas_mis$SEASON[i], seas_mis$season[i], seas_mis$season[i]))
logl("- Season labels follow the file names and SEASON column. Note that the two ",
     "DAB Set1 \"2017A\" trials have a Description START DATE of 2017-09-07, i.e. ",
     "the second (B) rainy season; the label does not affect the analysis because ",
     "every trial is a separate environment.")
logl("- Environment (`trial_id`) = site x season x series; ", uniqueN(dt[, .(set, site, season)]),
     " trials in ", uniqueN(dt[, .(site, season)]), " distinct site-seasons.")
logl("")

# --- 3. Genotype name harmonization ---------------------------------------------
dt[, genotype := toupper(gsub("\\s+", "", designation_raw))]
logl("## 3. Genotype (designation) harmonization")
logl("")
logl("- Rule: upper case and remove all white space (e.g. `DAB  474`, `DAB 474`, ",
     "`DAB474` -> `DAB474`; `CAL 96` -> `CAL96`). Before this step the 2017 and 2018 ",
     "DAB Set1 files shared no raw strings (`DAB 12` vs `DAB12`), nor did the 2012 ",
     "and 2015-2016 DAB Set2 files; afterward the entry lists of repeated trials agree.")
n_raw <- dt[, uniqueN(designation_raw)]; n_h <- dt[, uniqueN(genotype)]
logl("- Distinct raw strings: ", n_raw, "; distinct harmonized names: ", n_h, ".")
# Single explicit correction: `CA96` occurs once (DAB Set2 2012A) while the
# standard check CAL96 is present in every other export, including the
# three other DAB Set2 trials.
n_ca <- dt[genotype == "CA96", .N]
dt[genotype == "CA96", genotype := "CAL96"]
logl("- `CA96` (", n_ca, " plots, DAB Set2 2012A only) recoded to `CAL96`: CAL96 is the ",
     "common check present in every other export, including the three other ",
     "DAB Set2 trials, and CA96 is not a known line name.")
# Entry 157 in DAB Set2 2012B: rep 1 = DAB 550, rep 2 = DAB 356 (which already
# occupies entry 18 in both reps). Rep 2 is a transcription error.
fix <- dt[source_file == "DAB-SET_2 PYT1 2012B-Kawanda.xls" & entry_no == "157" & rep == 2 & genotype == "DAB356"]
dt[source_file == "DAB-SET_2 PYT1 2012B-Kawanda.xls" & entry_no == "157" & rep == 2 & genotype == "DAB356",
   genotype := "DAB550"]
logl("- DAB Set2 2012B, entry 157: rep 1 is DAB550 but rep 2 reads DAB356, which ",
     "already occupies entry 18 in both reps; ", nrow(fix), " plot recoded to DAB550.")
dup <- dt[, .(n = .N, n_entry = uniqueN(entry_no)), by = .(source_file, genotype)][n > 2]
logl("- Genotypes with more than two plots in one trial (repeated check entries, ",
     "e.g. CAL96 entered twice as `CAL96` and `CAL 96`): ", nrow(dup),
     " genotype-trial combinations; their plots are kept and pooled under one genotype.")
logl("")

# --- 4. Yield --------------------------------------------------------------------
# YDPL = GMPLOT / PLPLOT (g per plant); recorded YDHA = 200 * YDPL, i.e. yield per
# plant scaled to 200,000 plants/ha (kg/ha). The same scale is applied to all files.
dt[, ydha_recomp := PLANTS_PER_HA * GMPLOT / PLPLOT / 1000]
dt[!is.finite(ydha_recomp), ydha_recomp := NA_real_]
ratio <- dt[!is.na(YDHA) & !is.na(ydha_recomp) & ydha_recomp > 0,
            .(ratio_med = median(YDHA / ydha_recomp), ratio_min = min(YDHA / ydha_recomp),
              ratio_max = max(YDHA / ydha_recomp), mean_recorded = mean(YDHA)), by = source_file]
logl("## 4. Yield variable and unit checks")
logl("")
logl("- In every export, YDPL = GMPLOT / PLPLOT (g per plant) and recorded YDHA = ",
     "200 x YDPL, i.e. yield per plant scaled to 200,000 plants/ha (kg/ha), not ",
     "plot weight divided by plot area. `yield_kg_ha` is recomputed as ",
     "200 x GMPLOT / PLPLOT for every plot; this is the variable analyzed by Amongi ",
     "et al. (YDHA).")
bad <- ratio[ratio_max - ratio_min > 0.02 | abs(ratio_med - 1) > 0.01]
logl("- Files where recorded YDHA departs from 200 x GMPLOT / PLPLOT (all other files agree to rounding):")
for (i in seq_len(nrow(bad))) logl(sprintf(
  "  - `%s`: recorded / recomputed median %.3f (range %.2f-%.2f); recorded trial mean %.0f kg/ha.",
  bad$source_file[i], bad$ratio_med[i], bad$ratio_min[i], bad$ratio_max[i], bad$mean_recorded[i]))
logl("  - DAB Set3 2018B Kitengule: recorded YDHA = 2000 x YDPL (mean ~19,400 kg/ha), ",
     "a factor-10 scaling error; YDPL, GMPLOT and PLPLOT are on the same scale as ",
     "the other Kitengule trials, so the recomputed value (mean ~1,940 kg/ha) is used.")
logl("  - Drought Tolerant Coloured Beans 2015B Kawanda: recorded YDHA = GMPLOT x 10 / 3 ",
     "(area-based on a 3 m2 plot) rather than per-plant based; recomputed on the ",
     "per-plant scale used by all other exports.")
# Plots with a recorded YDHA but no GMPLOT/PLPLOT: keep recorded value if on the
# standard scale (all such files have ratio 1).
keep_rec <- dt[is.na(ydha_recomp) & !is.na(YDHA) & YDHA > 0]
dt[, yield_kg_ha := ydha_recomp]
dt[is.na(ydha_recomp) & !is.na(YDHA) & YDHA > 0, yield_kg_ha := YDHA]
logl("- ", nrow(keep_rec), " plots have YDHA but no GMPLOT or PLPLOT; recorded YDHA kept ",
     "(their files are on the standard 200 x YDPL scale).")
# Area-based yield for sensitivity analysis
dt[, area_m2 := fifelse(is.na(PlotArea), DEFAULT_AREA_M2, PlotArea)]
dt[, yield_area_kg_ha := GMPLOT * 10 / area_m2]
logl("- A second, area-based yield `yield_area_kg_ha` = GMPLOT (g) x 10 / plot area ",
     "(m2; 4.5 m2 in every file that reports it) is also written for sensitivity ",
     "analysis. It does not correct for stand and is not affected by the per-plant ",
     "extrapolation.")
logl("")

# --- 5. Exclusions ---------------------------------------------------------------
dt[, stand_rel := PLPLOT / median(PLPLOT, na.rm = TRUE), by = source_file]
dt[, exclude_reason := NA_character_]
dt[is.na(yield_kg_ha) | yield_kg_ha <= 0, exclude_reason := "missing_or_zero_yield"]
dt[is.na(exclude_reason) & !is.na(PLPLOT) & (PLPLOT < MIN_PLANTS | stand_rel < MIN_STAND_REL),
   exclude_reason := "low_stand"]

# Residual outliers: per trial, mixed model yield ~ rep + (1|genotype), one pass.
# With two replicates a fixed genotype effect gives both plots of an entry the
# same absolute residual; shrinking the genotype effect lets the deviant plot
# carry the larger residual.
dt[, trial_id := paste(set, site, season, sep = "_")]
dt[, outlier_z := NA_real_]
for (tid in unique(dt$trial_id)) {
  idx <- dt[, which(trial_id == tid & is.na(exclude_reason))]
  d <- dt[idx]
  if (nrow(d) < 10 || uniqueN(d$rep) < 2) next
  fit <- suppressMessages(lmer(yield_kg_ha ~ factor(rep) + (1 | genotype), data = d))
  dt[idx, outlier_z := residuals(fit) / sigma(fit)]
}
dt[is.na(exclude_reason) & !is.na(outlier_z) & abs(outlier_z) > OUTLIER_Z,
   exclude_reason := "residual_outlier"]

logl("## 5. Plot exclusions")
logl("")
logl("Excluded plots are kept in `zudpep_plots.csv` with `exclude = TRUE` and a reason; ",
     "the variance-component scripts use `exclude == FALSE` only.")
logl("")
logl("- `missing_or_zero_yield`: no usable yield (", dt[exclude_reason == "missing_or_zero_yield", .N],
     " plots; includes plots with zero harvested plants and one recorded YDHA = 0 with no plot weight).")
logl("- `low_stand`: fewer than ", MIN_PLANTS, " harvested plants or a stand below ",
     MIN_STAND_REL * 100, "% of the trial median (", dt[exclude_reason == "low_stand", .N],
     " plots). Yield per hectare is extrapolated from yield per plant, which is ",
     "unreliable on very small stands (e.g. 5 plants -> 23,360 kg/ha).")
logl("- `residual_outlier`: |standardized conditional residual| > ", OUTLIER_Z, " from a per-trial ",
     "mixed-model fit yield ~ rep + (1|genotype) on the remaining plots (",
     dt[exclude_reason == "residual_outlier", .N], " plots).")
logl("")
ex_tab <- dcast(dt[, .N, by = .(trial_id, reason = fifelse(is.na(exclude_reason), "kept", exclude_reason))],
                trial_id ~ reason, value.var = "N", fill = 0)
logl("| trial_id | ", paste(setdiff(names(ex_tab), "trial_id"), collapse = " | "), " |")
logl("|", paste(rep("---|", ncol(ex_tab)), collapse = ""))
for (i in seq_len(nrow(ex_tab))) logl("| ", paste(unlist(ex_tab[i]), collapse = " | "), " |")
logl("")

# --- 6. Design factors -------------------------------------------------------------
logl("## 6. Design")
logl("")
logl("- All trials with a Description sheet are resolvable incomplete-block designs ",
     "(BMS `RIBD`, alpha-lattice type) with 2 replicates; incomplete blocks are ",
     "numbered within replicate, so the block factor is rep:block.")
nb <- dt[, .(nblk = uniqueN(na.omit(block))), by = trial_id][nblk <= 1]
logl("- Trials with no block information (analyzed as RCBD): ",
     if (nrow(nb)) paste(nb$trial_id, collapse = ", ") else "none", ".")
logl("")

# --- 7. Write -------------------------------------------------------------------
dt[, exclude := !is.na(exclude_reason)]
out <- dt[, .(trial_id, set, site, season, rep = as.integer(rep),
              block = as.integer(block), plot_no, entry_no, genotype, designation_raw,
              yield_kg_ha = round(yield_kg_ha, 2), yield_area_kg_ha = round(yield_area_kg_ha, 2),
              plants_harvested = PLPLOT, plot_weight_g = GMPLOT, ydha_recorded = YDHA,
              exclude, exclude_reason, source_file)]
setorder(out, set, site, season, rep, block, plot_no)
fwrite(out, file.path(out_dir, "zudpep_plots.csv"))

summ <- out[exclude == FALSE, .(n_plots = .N, n_geno = uniqueN(genotype), n_rep = uniqueN(rep),
                                n_block = uniqueN(na.omit(block)),
                                mean_kg_ha = round(mean(yield_kg_ha)),
                                cv_pct = round(100 * sd(yield_kg_ha) / mean(yield_kg_ha), 1)),
            by = .(set, trial_id)]
logl("## 7. Final data")
logl("")
logl("- Plots written: ", nrow(out), "; analyzable (exclude = FALSE): ", out[exclude == FALSE, .N],
     "; trials: ", uniqueN(out$trial_id), "; harmonized genotypes: ", uniqueN(out$genotype), ".")
logl("")
logl("| set | trial_id | plots | genotypes | reps | blocks | mean kg/ha | CV % |")
logl("|---|---|---|---|---|---|---|---|")
for (i in seq_len(nrow(summ))) logl("| ", paste(unlist(summ[i]), collapse = " | "), " |")
writeLines(log_lines, file.path(out_dir, "zudpep_cleaning_log.md"))

cat("Wrote", nrow(out), "plots (", out[exclude == FALSE, .N], "analyzable ) to",
    file.path(out_dir, "zudpep_plots.csv"), "\n")
