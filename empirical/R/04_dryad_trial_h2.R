# ============================================================================
# Empirical calibration — Step 4: per-trial yield h2 from published summaries
# ============================================================================
# Source: Dryad doi:10.5061/dryad.dz08kpsbz (427 common bean genotypes; single-
# trial ANOVA per environment, Supplementary Table 2). Only variance components
# are available (no plot data), so h2_w = Vg / (Vg + Vres) is computed for YDHA
# per environment and reported as a separate source next to the plot-level
# per-trial estimates from ZUDPEP and TSEZVG.
# Output: empirical/outputs/dryad_trial_h2.csv
#         empirical/outputs/per_trial_h2_by_source.csv   (all sources, not pooled)
#         empirical/outputs/per_trial_h2_by_source.md
#
# Usage (from the project root):
#   Rscript empirical/R/04_dryad_trial_h2.R [path/to/Dryad_dz08kpsbz/x]

source("empirical/R/varcomp_utils.R")

args <- commandArgs(trailingOnly = TRUE)
src_dir <- if (length(args) >= 1) args[1] else
  "data/external/bean_public_2026-10-10/datasets/Dryad_dz08kpsbz/x"
tsezvg_src <- "data/external/bean_public_2026-10-10/datasets/TSEZVG/x/TPG_Phenotypedata.tab"
out_dir <- "empirical/outputs"

# The file is Latin-1 encoded (superscript in the H2 label); read as text.
read_latin1 <- function(f) {
  txt <- iconv(readLines(f, warn = FALSE, encoding = "latin1"), from = "latin1", to = "UTF-8")
  suppressWarnings(fread(text = txt, skip = 1, header = TRUE, fill = TRUE, sep = ",", colClasses = "character"))
}
num <- function(z) suppressWarnings(as.numeric(gsub("[^0-9.eE+-]", "", z)))

t2 <- read_latin1(file.path(src_dir, "Supplementary Table 2.csv"))
t2 <- t2[nzchar(Environment) & !is.na(num(No.))]
stat <- function(s) t2[grepl(s, Statistic), .(Environment, v = YDHA)]
dry <- Reduce(function(a, b) merge(a, b, by = "Environment"), list(
  stat("^Genotype variance")[, .(Environment, Vg_raw = v)],
  stat("^Residual variance")[, .(Environment, Ve_raw = v)],
  stat("heritability")[, .(Environment, H2_reported = num(v))],
  stat("^Grand Mean")[, .(Environment, mean_kg_ha = num(v))]))
dry[, `:=`(Vg = num(Vg_raw), Ve = num(Ve_raw))]
dry[, h2_w := Vg / (Vg + Ve)]
# Implied replicates per genotype from the reported entry-mean H2
dry[, r_implied := fifelse(H2_reported > 0 & H2_reported < 1, Ve * H2_reported / (Vg * (1 - H2_reported)), NA_real_)]
dry[, site := fcase(grepl("^Kag", Environment), "Kagera (Kitengule)", grepl("^Kaw", Environment), "Kawanda",
                    grepl("^Rwe", Environment), "Rwebitaba", default = NA_character_)]
dry[, season := paste0("20", sub("^[A-Za-z]+", "", Environment))]
dry[, vg_boundary := Vg <= 0]
fwrite(dry[, .(environment = Environment, site, season, Vg, Ve, h2_w, H2_reported, r_implied,
               mean_kg_ha, vg_boundary, source = "Dryad dz08kpsbz Suppl. Table 2")],
       file.path(out_dir, "dryad_trial_h2.csv"))

# --- Germplasm overlap with TSEZVG -------------------------------------------------
t1 <- read_latin1(file.path(src_dir, "Supplementary Table 1.csv"))
t1 <- t1[grepl("^GA-", Genotype_ID)]
norm <- function(z) toupper(gsub("[^A-Za-z0-9]", "", z))
ts <- fread(tsezvg_src)
setnames(ts, make.names(names(ts)))
ts[, key := norm(DESIGNATION)]
dk <- unique(norm(t1$GenotypeName))
ov_all  <- sum(dk %in% ts$key)
ov_2018 <- ts[Year == 2018 & !is.na(GY), .(n_trial_geno = uniqueN(key), shared = sum(unique(key) %in% dk)),
              by = .(TrialNo, LOCATION)]

# --- All per-trial estimates side by side ---------------------------------------------
zt <- fread(file.path(out_dir, "zudpep_trial_h2.csv"))[yield_var == "yield_kg_ha"]
tt <- fread(file.path(out_dir, "tsezvg_trial_h2.csv"))
all_src <- rbind(
  zt[, .(source = "ZUDPEP (plot data)", trial = trial_id, habit = "Bush", Vg, Ve, h2_w, vg_boundary)],
  tt[, .(source = "TSEZVG (plot data)", trial = trial_id, habit = growth_habit, Vg, Ve, h2_w, vg_boundary)],
  dry[, .(source = "Dryad dz08kpsbz (published ANOVA)", trial = Environment, habit = "Mixed (427 genotypes)",
          Vg, Ve, h2_w, vg_boundary)])
fwrite(all_src, file.path(out_dir, "per_trial_h2_by_source.csv"))

L <- character(); w <- function(...) L <<- c(L, paste0(...))
w("# Per-trial within-environment yield heritability by source")
w("")
w("Generated by `empirical/R/04_dryad_trial_h2.R` (", format(Sys.Date()), "). h2_w = Vg/(Vg+Ve) ",
  "from single-trial fits. Per-trial Vg includes the genotype x environment variance of that ",
  "trial, so these values estimate (Vg+Vge)/(Vg+Vge+Ve) in multi-environment terms and exceed ",
  "the multi-environment h2_w. Sources are reported separately and not pooled.")
w("")
w("| source | trials | median | IQR | range | Vg at 0 |")
w("|---|---|---|---|---|---|")
for (s in unique(all_src$source)) {
  ds <- dist_summary(all_src[source == s, h2_w])
  w("| ", s, " | ", ds$n, " | ", fmt(ds$median), " | ", fmt(ds$q25), "-", fmt(ds$q75), " | ",
    fmt(ds$min), "-", fmt(ds$max), " | ", all_src[source == s, sum(vg_boundary)], " |")
}
w("")
w("## Dryad dz08kpsbz, YDHA single-trial ANOVA (Supplementary Table 2)")
w("")
w("| environment | Vg | Vres | h2_w | H2 reported (entry mean) | implied reps | mean kg/ha |")
w("|---|---|---|---|---|---|---|")
for (i in seq_len(nrow(dry))) with(dry[i], w("| ", Environment, " | ", fmt0(Vg), " | ", fmt0(Ve), " | ",
  fmt(h2_w), " | ", fmt(H2_reported), " | ", ifelse(is.na(r_implied), "", fmt(r_implied, 1)), " | ", fmt0(mean_kg_ha), " |"))
w("")
w("Significance stars were stripped from the variance values. The reported H2 equals ",
  "Vg/(Vg+Vres/r) with r of about 2, i.e. an entry-mean value; h2_w is the plot-level ratio.")
w("")
w("## Overlap with TSEZVG")
w("")
w("- Dryad genotype names matching a TSEZVG designation (case and punctuation ignored): ",
  ov_all, " of ", length(dk), ".")
w("- TSEZVG 2018 trials (Kawanda, Kitengule = Kagera, Kachwekano) and the number of their ",
  "genotypes also in the Dryad panel:")
for (i in seq_len(nrow(ov_2018))) w("  - trial ", ov_2018$TrialNo[i], " (", ov_2018$LOCATION[i], "): ",
  ov_2018$shared[i], " of ", ov_2018$n_trial_geno[i])
writeLines(L, file.path(out_dir, "per_trial_h2_by_source.md"))
cat("Done.\n")
